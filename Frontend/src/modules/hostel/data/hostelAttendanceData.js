// Helper to create default daily attendance mapping
export const createDefaultAttendanceMap = (mode = "morning") => {
  const inTime = mode === "morning" ? "07:00 AM" : "08:00 PM";
  const outTime = mode === "morning" ? "08:30 AM" : "09:30 PM";

  const map = {};
  INITIAL_ATTENDANCE_STUDENTS.forEach((student) => {
    map[student.id] = {
      status: "Present",
      inTime: inTime,
      outTime: outTime,
    };
  });
  return map;
};

// Sample monthly breakdown data for Monthly Attendance view
export const MONTHLY_ATTENDANCE_DATA = INITIAL_ATTENDANCE_STUDENTS.map((st, idx) => {
  const totalDays = 30;
  // Realistic variance
  const present = idx % 5 === 0 ? 29 : idx % 3 === 0 ? 28 : idx % 7 === 0 ? 27 : 30;
  const absent = idx % 7 === 0 ? 1 : 0;
  const leave = idx % 5 === 0 ? 1 : idx % 3 === 0 ? 2 : idx % 7 === 0 ? 1 : 0;
  const halfDay = idx % 7 === 0 ? 1 : 0;
  const percentage = Math.round(((present + halfDay * 0.5) / totalDays) * 100);

  return {
    ...st,
    totalDays,
    present,
    absent,
    leave,
    halfDay,
    percentage,
  };
});

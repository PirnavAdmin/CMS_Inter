/**
 * Enriches any list of examinations with complete coverage for
 * Intermediate 1st Year, Intermediate 2nd Year, and all groups (MPC, BiPC, CEC, MBIPC).
 * Ensures 100% preservation of all authentic backend records and attaches campusId: 1.
 */
export const enrichExaminations = (rawBackendExams = []) => {
  const backendList = Array.isArray(rawBackendExams) ? rawBackendExams : [];
  const existingCodes = new Set(
    backendList.map((e) => String(e.code || e.examCode || "").trim().toLowerCase())
  );
  const existingIds = new Set(
    backendList.map((e) => String(e.id || e.examinationId || "").trim())
  );

  // Filter supplemental examinations to only include ones not already in backendList
  const additions = SUPPLEMENTAL_EXAMINATIONS.filter((supp) => {
    const codeMatch = supp.code && existingCodes.has(supp.code.toLowerCase());
    const idMatch = supp.id && existingIds.has(String(supp.id));
    return !codeMatch && !idMatch;
  }).map((supp) => ({
    ...supp,
    campusId: 1,
    campus: { id: 1, campusId: 1, name: "Main Campus" },
  }));

  return [...backendList, ...additions];
};

